"""
core/dose_accumulation.py — Multi-fraction dose accumulation with propagation
of the inter-fraction uncertainty and (optional) adaptive-RT extrapolation.

Base model (sum over the m fractions already delivered, assuming independence):
    D_acc(x)   = sum_i  w_i  * D_i(x)              i in [1..m]
    Var_acc(x) = sum_i  w_i^2 * Var_i(x)
    sigma_acc  = sqrt(Var_acc)

Adaptive extrapolation (optional, n_total/m_delivered specified):
    Given the full plan of n fractions and m already delivered, the dose expected
    at the end of treatment is estimated by linear scaling:
        D_pred = (n/m) * D_acc
        sigma_pred = (n/m) * sigma_acc
    The uncertainty scales like the dose because we assume that the remaining
    n-m fractions are statistically analogous to the mean of the first m.
Input for each fraction: dose_mean.npy + dose_std.npy generated by PASS 4
(`core/dose_propagation.DosePropagator`), already aligned to the fixed grid.

Methodological note: inter-fraction independence is a conservative
simplification. The DIR uncertainty of fractions of the same patient may be
correlated (same motion pattern). The independence assumption slightly
overestimates the total variance.
"""

import json
import os
from typing import Optional

import numpy as np


class DoseAccumulator:
    def __init__(self, fixed_shape: tuple, dtype=np.float32,
                 n_total: Optional[int] = None,
                 m_delivered: Optional[int] = None):
        # fixed_shape is the (Z, Y, X) shape of the fixed-CT grid, shared
        # by all fractions after PASS 4.
        # n_total/m_delivered enable adaptive-RT extrapolation (optional):
        # if both are specified and n>m, save() also emits
        # dose_predicted_full.npy + dose_predicted_full_std.npy.
        self.fixed_shape = tuple(fixed_shape)
        self.dtype = dtype
        self.n_total = int(n_total) if n_total is not None else None
        self.m_delivered = int(m_delivered) if m_delivered is not None else None
        self.mean_total = np.zeros(self.fixed_shape, dtype=dtype)
        self.var_total = np.zeros(self.fixed_shape, dtype=dtype)
        self.entries = []  # metadata for JSON

    def add(self, dose_mean: np.ndarray, dose_std: np.ndarray,
            weight: float, frac_id: str) -> None:
        if dose_mean.shape != self.fixed_shape:
            raise ValueError(
                f"Fraction '{frac_id}': dose_mean shape {dose_mean.shape} "
                f"!= fixed_shape {self.fixed_shape}. All fractions must "
                "produce dose-on-fixed with an identical grid (same fixed CT).")
        if dose_std.shape != self.fixed_shape:
            raise ValueError(
                f"Frazione '{frac_id}': dose_std shape {dose_std.shape} "
                f"!= fixed_shape {self.fixed_shape}.")
        w = float(weight)
        dose_mean_f = dose_mean.astype(self.dtype, copy=False)
        var_i = (dose_std.astype(self.dtype, copy=False)) ** 2
        self.mean_total += w * dose_mean_f
        self.var_total += (w ** 2) * var_i
        self.entries.append({
            "id": frac_id,
            "weight": w,
            "mean_min": float(dose_mean_f.min()),
            "mean_max": float(dose_mean_f.max()),
            "std_min": float(dose_std.min()),
            "std_max": float(dose_std.max()),
        })

    def finalize(self) -> dict:
        std_total = np.sqrt(np.clip(self.var_total, 0.0, None))
        m_eff = self.m_delivered if self.m_delivered is not None else len(self.entries)
        n_eff = self.n_total
        result = {
            "mean": self.mean_total,
            "std": std_total,
            "metadata": {
                "model": "independent_inter_fraction",
                "n_fractions": len(self.entries),
                "fractions": self.entries,
                "total": {
                    "mean_min": float(self.mean_total.min()),
                    "mean_max": float(self.mean_total.max()),
                    "std_min": float(std_total.min()),
                    "std_max": float(std_total.max()),
                },
            },
        }
        # Adaptive-RT extrapolation: linear scaling by n/m if requested.
        if n_eff is not None and m_eff > 0 and n_eff != m_eff:
            scale = float(n_eff) / float(m_eff)
            predicted_mean = (scale * self.mean_total).astype(self.dtype)
            predicted_std = (scale * std_total).astype(self.dtype)
            result["predicted_mean"] = predicted_mean
            result["predicted_std"] = predicted_std
            result["metadata"]["extrapolation"] = {
                "n_total": int(n_eff),
                "m_delivered": int(m_eff),
                "scale_factor": scale,
                "predicted": {
                    "mean_min": float(predicted_mean.min()),
                    "mean_max": float(predicted_mean.max()),
                    "std_min": float(predicted_std.min()),
                    "std_max": float(predicted_std.max()),
                },
            }
        return result

    def save(self, out_dir: str) -> dict:
        os.makedirs(out_dir, exist_ok=True)
        result = self.finalize()
        np.save(os.path.join(out_dir, "dose_accumulated.npy"), result["mean"])
        np.save(os.path.join(out_dir, "dose_accumulated_std.npy"), result["std"])
        if "predicted_mean" in result:
            np.save(os.path.join(out_dir, "dose_predicted_full.npy"), result["predicted_mean"])
            np.save(os.path.join(out_dir, "dose_predicted_full_std.npy"), result["predicted_std"])
        with open(os.path.join(out_dir, "accumulation_metadata.json"), "w") as f:
            json.dump(result["metadata"], f, indent=2)
        return result


def load_fraction_outputs(fraction_subdir: str) -> Optional[tuple]:
    # Returns (dose_mean, dose_std) if present and of consistent shape, otherwise None.
    mean_path = os.path.join(fraction_subdir, "dose_mean.npy")
    std_path = os.path.join(fraction_subdir, "dose_std.npy")
    if not (os.path.exists(mean_path) and os.path.exists(std_path)):
        return None
    try:
        mean = np.load(mean_path)
        std = np.load(std_path)
    except Exception:
        return None
    if mean.shape != std.shape:
        return None
    return mean, std
